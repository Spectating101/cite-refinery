"""Readable finding-first dossiers; never mistake metadata or proposal for proof."""
from __future__ import annotations
from typing import Any


def _safe(text: str, limit: int = 1100) -> str:
    return str(text or "").replace("\n", " ").replace("\r", " ").strip()[:limit]


def render(report: dict[str, Any]) -> str:
    if report.get("schema") == "cite_refinery.cross_layer_stack.v1":
        return _render_graph(report)
    if report.get("schema") == "cite_refinery.cross_layer_alignment.v1":
        return _render_candidates(report)
    raise ValueError("unsupported cross-layer report type")


def _render_graph(report: dict[str, Any]) -> str:
    out = ["# Cross-layer problem intelligence — reviewed graph",
           "", "Source-bounded candidate interpretations, not independently verified results.", ""]
    for problem in report["problems"]:
        out.extend(["## "+_safe(problem["problem"]["statement"]), ""])
        for label, key in (("Practical observation", "practical"),
                           ("Academic mechanism / method", "academic"),
                           ("Implementation / program", "implementations")):
            out.append("**"+label+"**")
            if problem[key]:
                for record in problem[key]:
                    out.append("- "+_safe(record["statement"],600)+" ["+record["edge_status"]+"]")
            else:
                out.append("- Not linked in this reviewed graph (not necessarily absent in the world).")
            out.append("")
        if problem["findings"]:
            out.append("**Interpreted findings**")
            for finding in problem["findings"]:
                out.append("- **"+finding["type"].replace("_"," ").capitalize()+"**: "+_safe(finding["interpretation"]))
                out.append("  - Why: "+_safe(finding["why"]))
                out.append("  - Next check: "+_safe(finding["next_check"]))
                if finding["source_refs"]:
                    out.append("  - Inspect sources: "+", ".join(finding["source_refs"][:6]))
                out.append("  - Status: "+finding["review_state"])
        else:
            out.append("**No validated cross-layer interpretation yet**. More explicit reviewed relationships are required.")
        out.extend(["","---",""])
    if not report["problems"]:
        out.append("No problem could be assembled from explicit source-reviewed edges.")
    out.append("**Limit:** absence of evidence in this graph is not evidence of worldwide nonexistence; source-review relationships are not proof of causal effectiveness.")
    return "\n".join(out)+"\n"


def _render_candidates(report: dict[str, Any]) -> str:
    out = ["# Cross-layer candidate dossier — "+_safe(report.get("topic","")),
           "", "**UNVERIFIED: generated by a model from earlier model readings, not the original texts.**", ""]
    if report["missing_layers"]:
        out.extend(["Missing represented perspectives: "+", ".join(report["missing_layers"]), ""])
    for a in report["alignments"]:
        out.extend(["## "+a["id"], "", "**Mechanism**: "+a["mechanism"], "",
                    "**Interpretation**: "+a["interpretation"], "",
                    "**Implementation fit**: "+a["solution_fit"], "",
                    "**Evidence tension**: "+a["evidence_tension"], "",
                    "**Counterargument**: "+a["counterargument"], "",
                    "**What to test next**: "+a["next_test"], "",
                    "**Source readings to verify**:"])
        for layer in ("practical","academic","program"):
            if not a["perspectives"][layer]:
                out.append("- "+layer+": no mapped source in this candidate chain")
            for r in a["perspectives"][layer]:
                out.append("- "+layer+": "+r["source_id"]+" — "+_safe(r["source_reading"],500)+" ("+r["source_url"]+")")
        out.extend(["", "Status: **"+a["status"]+"**", "", "---", ""])
    if not report["alignments"]:
        out.append("No cross-layer claim survived the source-role and scope gates. Do not force one.")
    out.append("**Limit:** not source-validated entailment, independent discovery proof, or intervention outcome assessment.")
    return "\n".join(out)+"\n"
